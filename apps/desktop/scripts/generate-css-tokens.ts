import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import {
  spacing,
  radius,
  typography,
  TYPOGRAPHY_TOKEN_KEYS,
  BREAKPOINT_KEYS,
  BREAKPOINT_MIN_WIDTH,
  SCALE_FACTOR_KEYS,
  type Breakpoint,
} from '../src/design';

const VALUES_OUTPUT_PATH = resolve(__dirname, '../src/styles/generated/tokens.css');
const TIERS_OUTPUT_PATH = resolve(__dirname, '../src/styles/generated/size-tiers.css');

const REM_DIVISOR = 16;

function toRem(value: number): string {
  const rem = value / REM_DIVISOR;
  return `${Number(rem.toFixed(4))}rem`;
}

function toKebabCase(key: string): string {
  return key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function indent(lines: string, spaces: number): string {
  const pad = ' '.repeat(spaces);
  return lines
    .split('\n')
    .map((line) => (line ? pad + line : line))
    .join('\n');
}

// PART 1 — RAW VALUES
function buildScaleValues(
  prefix: string,
  scale: Partial<Record<Breakpoint, Record<string, number>>>,
): string {
  const decls: string[] = [];

  for (const breakpoint of BREAKPOINT_KEYS) {
    const tier = scale[breakpoint];
    if (!tier) continue;
    for (const key of SCALE_FACTOR_KEYS) {
      decls.push(`--${prefix}-${breakpoint}-${key}: ${toRem(tier[key])};`);
    }
  }

  return [':root {', indent(decls.join('\n'), 2), '}'].join('\n');
}

function buildTypographyValues(): string {
  const decls: string[] = [];

  for (const name of TYPOGRAPHY_TOKEN_KEYS) {
    const scale = typography[name];
    for (const key of SCALE_FACTOR_KEYS) {
      decls.push(`--font-${toKebabCase(name)}-${key}: ${toRem(scale[key])};`);
    }
  }

  return [':root {', indent(decls.join('\n'), 2), '}'].join('\n');
}

// PART 2 — SIZE-TIER SELECTION
const SIZE_TIER_KEYS = SCALE_FACTOR_KEYS;

const AUTO_TIER_THRESHOLDS: Array<{ sf: (typeof SIZE_TIER_KEYS)[number]; minWidth: number }> = [
  { sf: 'sfb', minWidth: BREAKPOINT_MIN_WIDTH.xs },
  { sf: 'sfc', minWidth: BREAKPOINT_MIN_WIDTH.md },
  { sf: 'sfd', minWidth: BREAKPOINT_MIN_WIDTH.lg },
  { sf: 'sfe', minWidth: BREAKPOINT_MIN_WIDTH.xxl },
];

function consumableTokenNames(): Array<{ cssVar: string; sourceVar: (sf: string) => string }> {
  const names: Array<{ cssVar: string; sourceVar: (sf: string) => string }> = [];

  for (const [prefix, scale] of [
    ['space', spacing],
    ['radius', radius],
  ] as const) {
    for (const breakpoint of BREAKPOINT_KEYS) {
      if (!scale[breakpoint]) continue;
      names.push({
        cssVar: `--${prefix}-${breakpoint}`,
        sourceVar: (sf) => `--${prefix}-${breakpoint}-${sf}`,
      });
    }
  }

  for (const name of TYPOGRAPHY_TOKEN_KEYS) {
    names.push({
      cssVar: `--font-${toKebabCase(name)}`,
      sourceVar: (sf) => `--font-${toKebabCase(name)}-${sf}`,
    });
  }

  return names;
}

function buildSizeTierBlocks(): string {
  const tokens = consumableTokenNames();
  const out: string[] = [];

  // 1. DEFAULT MANUAL MODE: Default unconditionally to "sfc"
  // If no [data-size-tier] attribute is present on <html>, the app runs in manual sfc mode.
  out.push(
    ':root {',
    indent(tokens.map((t) => `${t.cssVar}: var(${t.sourceVar('sfc')});`).join('\n'), 2),
    '}',
    '',
  );

  // 2. AUTO MODE (Opt-in via data-size-tier="auto")
  // Base auto-mode fallback for narrow viewports (< 480px)
  out.push(
    `:root[data-size-tier='auto'] {`,
    indent(tokens.map((t) => `${t.cssVar}: var(${t.sourceVar('sfa')});`).join('\n'), 2),
    '}',
    '',
  );

  // Responsive @media tiers for Auto Mode
  for (const { sf, minWidth } of AUTO_TIER_THRESHOLDS) {
    out.push(
      `@media (min-width: ${minWidth}px) {`,
      `  :root[data-size-tier='auto'] {`,
      indent(tokens.map((t) => `${t.cssVar}: var(${t.sourceVar(sf)});`).join('\n'), 4),
      '  }',
      '}',
      '',
    );
  }

  // 3. EXPLICIT MANUAL PINS (data-size-tier="sfa"..."sfe")
  for (const sf of SIZE_TIER_KEYS) {
    out.push(
      `:root[data-size-tier='${sf}'] {`,
      indent(tokens.map((t) => `${t.cssVar}: var(${t.sourceVar(sf)});`).join('\n'), 2),
      '}',
      '',
    );
  }

  return out.join('\n');
}

function buildValuesFile(): string {
  return [
    '/* AUTO-GENERATED by scripts/generate-css-tokens.ts — do not edit by hand. */',
    '/* Raw values only. Does not decide which sf variant is active — see size-tiers.css. */',
    '',
    '/* ---- Spacing ---- */',
    buildScaleValues('space', spacing),
    '',
    '/* ---- Radius ---- */',
    buildScaleValues('radius', radius),
    '',
    '/* ---- Typography ---- */',
    buildTypographyValues(),
    '',
  ].join('\n');
}

function buildTiersFile(): string {
  return [
    '/* AUTO-GENERATED by scripts/generate-css-tokens.ts — do not edit by hand. */',
    '/* Resolves consumable tokens to specific sf variants. Default is manual "sfc".',
    '   Use data-size-tier="auto" for responsive scaling, or data-size-tier="sfa".."sfe" for manual pins. */',
    '',
    buildSizeTierBlocks(),
  ].join('\n');
}

mkdirSync(dirname(VALUES_OUTPUT_PATH), { recursive: true });
writeFileSync(VALUES_OUTPUT_PATH, buildValuesFile(), 'utf-8');
writeFileSync(TIERS_OUTPUT_PATH, buildTiersFile(), 'utf-8');
console.log(`Generated ${VALUES_OUTPUT_PATH}`);
console.log(`Generated ${TIERS_OUTPUT_PATH}`);
